int acp_game_patch_validate(const uint8_t *p,size_t bytes){
    if(!p||bytes<ACP_ALLOC_LUA_VA+sizeof(alloc_guard)||bytes<ACP_IDLE_VA+sizeof(idle_guard)||bytes<ACP_DIRECTORY_SIZE_VA+sizeof(directory_guard)||bytes<ACP_GC_STEP_VA+sizeof(gc_step_guard))return -1;
    return memcmp(p+ACP_ALLOC_LUA_VA,alloc_guard,sizeof(alloc_guard))||memcmp(p+ACP_IDLE_VA,idle_guard,sizeof(idle_guard))||memcmp(p+ACP_DIRECTORY_SIZE_VA,directory_guard,sizeof(directory_guard))||memcmp(p+ACP_GC_VA,gc_guard,sizeof(gc_guard))||memcmp(p+ACP_GC_VA+0x12,gc_loop_guard,sizeof(gc_loop_guard))||memcmp(p+ACP_GC_STEP_VA,gc_step_guard,sizeof(gc_step_guard))?-1:0;
}
int acp_gc_trampoline_build(uint32_t continuation,uint8_t out[24]){
    if(!out||!(continuation&1))return -1;
    memcpy(out,gc_step_guard,sizeof(gc_step_guard));out[14]=0x00;out[15]=0xbf;
    return acp_game_patch_build(continuation,out+16);
}
int acp_game_patch_build(uint32_t destination,uint8_t out[8]){
    if(!out||!destination||(!(destination&1)&&(destination&3)))return -1;
    const uint8_t instruction[4]={0xdf,0xf8,0x00,0xf0}; /* ldr.w pc,[pc,#0] */
    memcpy(out,instruction,4);for(unsigned i=0;i<4;i++)out[4+i]=(uint8_t)(destination>>(8*i));return 0;
}
